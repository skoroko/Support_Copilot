"""Write Mermaid views of both homework 6.3 graphs without invoking an LLM."""

from __future__ import annotations

import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.services.agent_graph import custom_graph, prebuilt_graph


OUTPUTS = {
    PROJECT_ROOT / "docs" / "agent-graph-custom.mmd": custom_graph,
    PROJECT_ROOT / "docs" / "agent-graph-prebuilt.mmd": prebuilt_graph,
}


def main() -> None:
    for destination, graph in OUTPUTS.items():
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Replace atomically instead of truncating the existing artifact.  On
        # Windows the file may have been generated by another sandbox identity
        # and still be replaceable through its writable parent directory.
        temporary = destination.with_suffix(f"{destination.suffix}.tmp")
        temporary.write_text(graph.get_graph().draw_mermaid(), encoding="utf-8")
        temporary.replace(destination)
        print(destination.relative_to(PROJECT_ROOT))


if __name__ == "__main__":
    main()
